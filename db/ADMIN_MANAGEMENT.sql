-- =========================================================

-- Посмотреть всех админов
SELECT 
    p.id,
    u.email,
    u.raw_user_meta_data->>'full_name' as name,
    p.role,
    p.updated_at
FROM profiles p
JOIN auth.users u ON p.id = u.id
WHERE p.role = 'admin'
ORDER BY p.updated_at DESC;

